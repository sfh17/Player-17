#!/usr/bin/env python3
"""Browser-17: build a ready Arch / Manjaro package (.pkg.tar.zst) without makepkg.

So the Arch package can be built on Ubuntu too, like the .rpm. Makes the same thing makepkg
does: .PKGINFO + .MTREE + the files, everything owned by root, then zstd (or xz if there is no
zstd on the computer — pacman installs both).

    mkarchpkg.py <stage dir> <dist dir> <name> <version> <arch> <desc> <url> <dep> [<dep>...]
"""
import gzip
import hashlib
import io
import os
import shutil
import subprocess
import sys
import tarfile
import time

stage, dist, name, version, arch, desc, url, *deps = sys.argv[1:]
pkgver = f"{version}-1"
now = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))


def walk(root):
    """Every path under root (relative, sorted, dirs before their contents)."""
    out = []
    for d, dirs, files in os.walk(root):
        dirs.sort()
        rel = os.path.relpath(d, root)
        if rel != ".":
            out.append(rel)
        for f in sorted(files):
            out.append(os.path.normpath(os.path.join(rel, f)))
        # symlinks to dirs are listed in dirs but not walked into
        for x in list(dirs):
            if os.path.islink(os.path.join(d, x)):
                out.append(os.path.normpath(os.path.join(rel, x)))
                dirs.remove(x)
    return out


paths = walk(stage)
size = sum(os.lstat(os.path.join(stage, p)).st_size for p in paths
           if os.path.isfile(os.path.join(stage, p)) and not os.path.islink(os.path.join(stage, p)))

# ---------------- .PKGINFO ----------------
pkginfo = [
    "# Generated by Browser-17 packaging/mkarchpkg.py",
    f"pkgname = {name}",
    f"pkgbase = {name}",
    "xdata = pkgtype=pkg",
    f"pkgver = {pkgver}",
    f"pkgdesc = {desc}",
    f"url = {url}",
    f"builddate = {now}",
    "packager = sfh17",
    f"size = {size}",
    f"arch = {arch}",
    "license = custom",
] + [f"depend = {d}" for d in deps]
pkginfo_bytes = ("\n".join(pkginfo) + "\n").encode()


# ---------------- .MTREE (what pacman -Qk checks the installed files against) ----------------
def esc(p):
    ok = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789/._-+,:@%=")
    return "".join(c if c in ok else "".join(f"\\{b:03o}" for b in c.encode()) for c in p)


def digests(data):
    return hashlib.md5(data).hexdigest(), hashlib.sha256(data).hexdigest()


lines = ["#mtree", "/set type=file uid=0 gid=0 mode=644"]
md5, sha = digests(pkginfo_bytes)
lines.append(f"./.PKGINFO time={now}.0 size={len(pkginfo_bytes)} md5digest={md5} sha256digest={sha}")
for p in paths:
    full = os.path.join(stage, p)
    st = os.lstat(full)
    mode = oct(st.st_mode & 0o7777)[2:]
    t = f"time={int(st.st_mtime)}.0"
    if os.path.islink(full):
        lines.append(f"./{esc(p)} {t} mode=777 type=link link={esc(os.readlink(full))}")
    elif os.path.isdir(full):
        lines.append(f"./{esc(p)} {t} mode={mode} type=dir")
    else:
        with open(full, "rb") as fh:
            md5, sha = digests(fh.read())
        lines.append(f"./{esc(p)} {t} mode={mode} size={st.st_size} md5digest={md5} sha256digest={sha}")
mtree = gzip.compress(("\n".join(lines) + "\n").encode(), mtime=now)


# ---------------- the archive ----------------
def root_owned(ti):
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = "root"
    return ti


def meta(arcname, data):
    ti = root_owned(tarfile.TarInfo(arcname))
    ti.size, ti.mtime, ti.mode = len(data), now, 0o644
    return ti, io.BytesIO(data)


os.makedirs(dist, exist_ok=True)
base = os.path.join(dist, f"{name}-{pkgver}-{arch}.pkg.tar")
with tarfile.open(base, "w", format=tarfile.GNU_FORMAT) as tar:
    tar.addfile(*meta(".PKGINFO", pkginfo_bytes))
    tar.addfile(*meta(".MTREE", mtree))
    for p in paths:
        tar.add(os.path.join(stage, p), arcname=p, recursive=False, filter=root_owned)

if shutil.which("zstd"):
    subprocess.run(["zstd", "-q", "-f", "-T0", "-19", "--rm", base], check=True)
    out = base + ".zst"
else:
    subprocess.run(["xz", "-f", "-T0", "-6", base], check=True)
    out = base + ".xz"
print("-> dist/" + os.path.basename(out))
